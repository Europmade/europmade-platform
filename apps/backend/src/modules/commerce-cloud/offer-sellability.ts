/**
 * Offer sales lifecycle helpers (Commerce Cloud).
 * Independent of Product Cloud publication_status.
 */

import { randomBytes } from "node:crypto"

export type OfferSalesStatus = "active" | "paused"

const SELLER_SKU_PREFIX = "EM-"

export function normalizeSellerSku(
  sku: string | null | undefined
): string | null {
  if (sku == null) return null
  const trimmed = String(sku).trim()
  return trimmed.length === 0 ? null : trimmed
}

/** Stable auto-SKU: EM-{year}-{6 random alphanumeric chars}. */
export function generateSellerSku(now: Date = new Date()): string {
  const year = now.getUTCFullYear()
  const suffix = randomBytes(3).toString("hex").toUpperCase()
  return `${SELLER_SKU_PREFIX}${year}-${suffix}`
}

export function isAutoGeneratedSellerSku(
  sku: string | null | undefined
): boolean {
  const normalized = normalizeSellerSku(sku)
  return !!normalized && normalized.startsWith(`${SELLER_SKU_PREFIX}`)
}

export function isOfferActiveForSale(
  salesStatus: string | null | undefined
): boolean {
  return (salesStatus ?? "active") === "active"
}

export function isOfferSellable(input: {
  sales_status?: string | null
  quantity_available?: number | null
}): boolean {
  return (
    isOfferActiveForSale(input.sales_status) &&
    (input.quantity_available ?? 0) > 0
  )
}
