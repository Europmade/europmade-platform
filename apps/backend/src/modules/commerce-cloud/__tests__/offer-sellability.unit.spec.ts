import { readFileSync } from "node:fs"
import { join } from "node:path"
import {
  isOfferActiveForSale,
  isOfferSellable,
  evaluateOfferSellability,
  storefrontAvailability,
  normalizeSellerSku,
  generateSellerSku,
  isAutoGeneratedSellerSku,
  type OfferSellabilityInput,
} from "../offer-sellability"
import { computeBuyBoxRanking, DEFAULT_BUY_BOX_WEIGHTS } from "../buy-box-engine"

describe("Offer sellability (P1A)", () => {
  it("normalizes seller SKU", () => {
    expect(normalizeSellerSku("  ABC-1  ")).toBe("ABC-1")
    expect(normalizeSellerSku("   ")).toBe(null)
    expect(normalizeSellerSku(null)).toBe(null)
  })

  it("generates stable EM-prefixed seller SKUs", () => {
    const sku = generateSellerSku(new Date("2026-06-01T00:00:00Z"))
    expect(sku).toMatch(/^EM-2026-[A-F0-9]{6}$/)
    expect(isAutoGeneratedSellerSku(sku)).toBe(true)
    expect(isAutoGeneratedSellerSku("BOSCH-001")).toBe(false)
  })

  it("treats paused offers as not sellable", () => {
    expect(isOfferActiveForSale("active")).toBe(true)
    expect(isOfferActiveForSale("paused")).toBe(false)
    const ready = sellableOffer()
    expect(isOfferSellable({ ...ready, sales_status: "paused" })).toBe(false)
    expect(isOfferSellable(ready)).toBe(true)
    expect(isOfferSellable({ ...ready, quantity_available: 0 })).toBe(false)
  })

  it("Buy Box ranking ignores zero-stock (paused filtered before engine)", () => {
    const result = computeBuyBoxRanking({
      identifier_id: "id_1",
      region_code: "NL",
      weights: DEFAULT_BUY_BOX_WEIGHTS,
      offers: [
        {
          offer_id: "off_active",
          seller_id: "sel_a",
          quantity_available: 5,
          base_price: 100,
          shipping_cost: 5,
        },
        {
          offer_id: "off_zero",
          seller_id: "sel_b",
          quantity_available: 0,
          base_price: 80,
          shipping_cost: 5,
        },
      ],
    })
    expect(result.ranked.map((r) => r.offer_id)).toEqual(["off_active"])
    expect(result.winning_offer_id).toBe("off_active")
  })
})

function sellableOffer(patch: Partial<OfferSellabilityInput> = {}): OfferSellabilityInput {
  return {
    has_offer: true,
    sales_status: "active",
    base_price: 25,
    has_inventory: true,
    quantity_available: 4,
    delivery_days_max: 3,
    shipping_profile_id: "shp_1",
    shipping_profile_status: "active",
    shipping_profile_serves_region: true,
    publication_status: "Gepubliceerd",
    approval_status: "Goedgekeurd",
    ...patch,
  }
}

describe("central offer sellability", () => {
  it("names every missing commercial fact and ignores approval", () => {
    const missing = evaluateOfferSellability({
      has_offer: false,
      publication_status: "Gepubliceerd",
      approval_status: "Afgekeurd",
    })
    expect(missing.sellable).toBe(false)
    expect(missing.reasons.map((reason) => reason.code)).toEqual(["missing_offer"])

    const price = evaluateOfferSellability(sellableOffer({ base_price: 0 }))
    expect(price.reasons.map((reason) => reason.message)).toContain(
      "Verkoopprijs moet groter zijn dan nul."
    )
    expect(
      evaluateOfferSellability(sellableOffer({ base_price: null })).reasons.map(
        (reason) => reason.code
      )
    ).toContain("invalid_price")
    expect(
      evaluateOfferSellability(
        sellableOffer({ has_inventory: false, quantity_available: null })
      ).reasons.map((reason) => reason.code)
    ).toContain("missing_inventory")
    expect(
      evaluateOfferSellability(sellableOffer({ delivery_days_max: null })).reasons.map(
        (reason) => reason.code
      )
    ).toContain("invalid_delivery")
    expect(
      evaluateOfferSellability(sellableOffer({ delivery_days_max: 400 })).reasons.map(
        (reason) => reason.message
      )
    ).toContain("Levertijd is ongeldig.")
    expect(
      evaluateOfferSellability(sellableOffer({ shipping_profile_id: null })).reasons.map(
        (reason) => reason.code
      )
    ).toContain("missing_shipping_profile")
    expect(
      evaluateOfferSellability(
        sellableOffer({ shipping_profile_serves_region: false })
      ).reasons.map((reason) => reason.code)
    ).toContain("invalid_shipping_profile")
    expect(
      evaluateOfferSellability(sellableOffer({ sales_status: "paused" })).reasons.map(
        (reason) => reason.code
      )
    ).toContain("sales_status")
    const unpublished = evaluateOfferSellability(
      sellableOffer({ publication_status: "In review", approval_status: "Goedgekeurd" })
    )
    expect(unpublished.published).toBe(false)
    expect(unpublished.offer_complete).toBe(true)
    expect(unpublished.sellable).toBe(false)
    expect(unpublished.reasons.map((reason) => reason.code)).toEqual(["not_published"])
  })

  it("keeps a published product published when stock is zero and sells it again when stock returns", () => {
    const reserved = { lines: [{ id: "ol_1", quantity: 1 }] }
    const empty = evaluateOfferSellability(sellableOffer({ quantity_available: 0 }))
    expect(empty).toMatchObject({
      sellable: false,
      published: true,
      offer_complete: true,
    })
    expect(empty.reasons.map((reason) => reason.code)).toEqual(["no_stock"])
    expect(reserved.lines).toEqual([{ id: "ol_1", quantity: 1 }])
    const restocked = evaluateOfferSellability(
      sellableOffer({ quantity_available: reserved.lines[0].quantity })
    )
    expect(restocked.sellable).toBe(true)
    expect(restocked.published).toBe(true)
    expect(reserved.lines).toEqual([{ id: "ol_1", quantity: 1 }])
    expect(
      storefrontAvailability({
        published: true,
        offers: [{ ships: true, decision: empty }],
      })
    ).toBe("out_of_stock")
    expect(
      storefrontAvailability({
        published: true,
        offers: [{ ships: true, decision: restocked }],
      })
    ).toBe("orderable")
  })

  it("uses the same function for seller, admin and storefront", () => {
    const decision = evaluateOfferSellability(sellableOffer())
    expect(isOfferSellable(sellableOffer())).toBe(decision.sellable)
    expect(
      evaluateOfferSellability(sellableOffer({ approval_status: "Afgekeurd" }))
    ).toEqual(decision)
    const root = join(__dirname, "../../../..")
    const files = [
      "src/api/store/product-cloud/product-manager.ts",
      "src/api/store/catalog/catalog-helpers.ts",
      "src/modules/commerce-cloud/service.ts",
      "src/api/admin/product-cloud/offers/[id]/route.ts",
      "src/api/store/commerce-cloud/offers/route.ts",
      "src/modules/commerce-cloud/bulk-offer-commerce.ts",
    ]
    for (const file of files) {
      expect(readFileSync(join(root, file), "utf8")).toContain("evaluateOfferSellability")
    }
  })
})
