/**
 * Generate a packing-slip PDF buffer from enriched order data.
 */
import PDFDocument from "pdfkit"

type PackingLine = {
  product_name: string
  variant_name?: string | null
  sku?: string | null
  quantity: number
}

type PackingInput = {
  order_number: string
  order_date: string
  seller_id: string
  customer_name: string | null
  shipping_address_lines: string[]
  carrier?: string | null
  tracking_code?: string | null
  lines: PackingLine[]
}

export async function generatePackingSlipPdf(
  input: PackingInput
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    // compress:false keeps text streams searchable for verification / tooling
    const doc = new PDFDocument({ size: "A4", margin: 50, compress: false })
    const chunks: Buffer[] = []
    doc.on("data", (c) => chunks.push(c as Buffer))
    doc.on("end", () => resolve(Buffer.concat(chunks)))
    doc.on("error", reject)

    // Single bilingual title block — do not repeat "Packing slip"
    doc.fontSize(18).fillColor("#000").text("EuropMade")
    doc.moveDown(0.2)
    doc.fontSize(12).fillColor("#333").text("Packing slip / Pakbon")
    doc.moveDown(1)

    doc.fillColor("#000").fontSize(11)
    doc.text(`Order: ${input.order_number}`)
    doc.text(`Date: ${input.order_date}`)
    doc.text(`Seller: ${input.seller_id}`)
    doc.moveDown()

    doc.fontSize(12).text("Ship to", { underline: true })
    doc.fontSize(11)
    if (input.customer_name) doc.text(input.customer_name)
    for (const line of input.shipping_address_lines) {
      if (line.trim()) doc.text(line.trim())
    }
    doc.moveDown()

    if (input.carrier || input.tracking_code) {
      doc.fontSize(12).text("Fulfilment", { underline: true })
      doc.fontSize(11)
      if (input.carrier) doc.text(`Carrier: ${input.carrier}`)
      if (input.tracking_code) doc.text(`Tracking: ${input.tracking_code}`)
      doc.moveDown()
    }

    doc.fontSize(12).text("Items", { underline: true })
    doc.moveDown(0.5)
    doc.fontSize(10)
    const headerY = doc.y
    doc.text("Qty", 50, headerY, { width: 40 })
    doc.text("Product / SKU", 100, headerY, { width: 440 })
    doc
      .moveTo(50, headerY + 14)
      .lineTo(545, headerY + 14)
      .stroke()
    doc.y = headerY + 18

    for (const line of input.lines) {
      const y = doc.y
      doc.text(String(line.quantity), 50, y, { width: 40 })
      const parts = [line.product_name]
      if (line.variant_name) parts.push(`(${line.variant_name})`)
      if (line.sku) parts.push(`SKU: ${line.sku}`)
      doc.text(parts.join("  "), 100, y, { width: 440 })
      doc.moveDown(0.5)
    }

    doc.moveDown(1.5)
    doc.fontSize(9).fillColor("#666").text("Generated by EuropMade")
    doc.end()
  })
}
